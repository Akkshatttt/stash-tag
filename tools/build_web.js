// Builds the static page for Cloudflare Pages: src/AppPage.html with the template tags filled, token left empty (the page reads #t=).
//   node tools/build_web.js   -> web/index.html   (Cloudflare build command; output directory "web")
// Also writes lib/shared.js: the pure Apps Script sources the Pages Function needs (label parser, part normaliser) as one ES module. That file
// is committed and tests/cloud_test.js fails if it is out of date, so a deploy never depends on this step having run first.
const fs = require('fs');
const path = require('path');
const { loadSrc } = require('../tests/load');

/** The label parser and normaliser the Cloudflare Function shares with Apps Script (one source of truth: src/). */
function buildShared() {
  const read = f => fs.readFileSync(path.join(__dirname, '..', 'src', f), 'utf8').split('\r\n').join('\n');
  return '// GENERATED by tools/build_web.js from src/Util.js, Config.js, Normalize.js, Barcode.js. Do not edit; run `node tools/build_web.js`.\n' +
    ['Util.js', 'Config.js', 'Normalize.js', 'Barcode.js'].map(read).join('\n') +
    '\nexport { SETTINGS, normPn, squash, fromDigikey_, fromMouser_, mergeLabels_, partKeys_, noPartWarning_ };\n';
}

function buildWeb() {
  const S = loadSrc();
  const html = fs.readFileSync(path.join(__dirname, '..', 'src', 'AppPage.html'), 'utf8');
  return html.replace('<?!= lib ?>', () => S.clientLib_())   // function replacement: the lib contains "$'"
    .replace('<?!= JSON.stringify(token) ?>', () => '""')
    .replace('<?!= JSON.stringify(categories) ?>', () => JSON.stringify(S.CATEGORIES));
}

if (require.main === module) {
  const root = path.join(__dirname, '..');
  fs.mkdirSync(path.join(root, 'web'), { recursive: true });
  fs.writeFileSync(path.join(root, 'web', 'index.html'), buildWeb());
  fs.mkdirSync(path.join(root, 'lib'), { recursive: true });
  fs.writeFileSync(path.join(root, 'lib', 'shared.js'), buildShared());
  console.log('wrote web/index.html, lib/shared.js');
}
module.exports = { buildWeb, buildShared };
